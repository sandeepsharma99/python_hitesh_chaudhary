# Polymorphism is a core concept of Object-Oriented Programming (OOP) that allows a single function, method, or operator to be used in different ways depending on the type or class of the object it is operating on. 

# Built-in Function

print(len("Hello"))   # Output: 5
print(len([1, 2, 3])) # Output: 3
print(len({'a': 1, 'b': 2})) # Output: 2







